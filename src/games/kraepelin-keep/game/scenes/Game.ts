/**
 * Game scene — owns the canvas gameplay.
 *
 * INPUT MODEL:
 *   - The universal Answer Pad (React/DOM) is always visible during play on
 *     every platform. A tap emits bridge "cast" {digit}.
 *   - PC keyboard 0-9/numpad casts directly (desktop only). Esc pauses.
 *   - Every input is a definite digit 0-9 — there is no "miscast" concept.
 *     A cast is always {correct digit -> matching enemy dies} or {wrong digit
 *     -> wrong-cast feedback + 0.5s lock}.
 *
 * TEN ELEMENT SPELL EFFECTS: on a correct kill, castFx(digit, x, y) dispatches
 * a distinct cosmetic effect per digit (0-9). No gameplay side effects.
 *
 * PACING: per-level (see LEVELS in tuning.ts).
 *
 * QUESTION MODEL (per-level): each wisp carries its own fixed question
 * generated by generateQuestion() based on the active level's operators.
 * Answer = last digit of the result. Uniqueness re-roll (max 20 tries) so
 * all airborne answers are distinct. Questions never change after spawn.
 */
