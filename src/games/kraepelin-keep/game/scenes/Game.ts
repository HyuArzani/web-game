  /** Ambient wisp trail: a 2px bone speck every ~180ms, fading in ~400ms. */
  private spawnWispTrail(w: Wisp): void {
    if (this.trailSpecks.length >= TUNING.WISP_TRAIL_CAP) {
      const old = this.trailSpecks.shift();
      if (old && old.active) old.destroy();
    }
    const s = this.add.image(
      w.container.x + Phaser.Math.Between(-6, 6),
      w.container.y - 6,
      "star",
    );
    s.setTintFill(C.bone);
    s.setScale(1);
    s.setAlpha(0.7).setDepth(2);
    this.trailSpecks.push(s);
    this.tweens.add({
      targets: s,
      alpha: 0,
      y: s.y - 6,
      duration: TUNING.WISP_TRAIL_LIFE_MS,
      onComplete: () => {
        s.destroy();
        const i = this.trailSpecks.indexOf(s);
        if (i >= 0) this.trailSpecks.splice(i, 1);
      },
    });
  }

  /* ----------------------------- gameover ---------------------------- */

  private gameover(): void {
    this.running = false;
    SFX.play("gameover");

    // Wizard defeat animation (staff dim + slump + fade, ~700ms, plays once)
    this.playGameOverAnimation();

    const elapsedMin = Math.max(
      0.0001,
      (this.time.now - this.runStartTime) / 60000,
    );
    const dpm = Math.round(this.correctCount / elapsedMin);
    const total = this.correctCount + this.wrongCount;
    const accuracy = total > 0 ? Math.round((this.correctCount / total) * 100) : 0;
    const bestStreak = maybeUpdateBestStreak(this.runBestStreak);
    void getBestStreak();

    // mode = majority cast source ("keys" if keyboard majority, else "pad").
    const mode: Mode =
      this.keyboardCasts > this.padCasts ? "keys" : "pad";
    bridge.emit(EV.gameover, {
      score: this.score,
      dpm,
      accuracy,
      bestStreak,
      mode,
      level: this.level,
    });
    this.emitHud();
  }

  /* ----------------------------- bridge ------------------------------- */

  private handleStart(p: StartPayload): void {
    const incoming = p?.level;
    if (
      incoming !== "veryEasy" &&
      incoming !== "easy" &&
      incoming !== "normal" &&
      incoming !== "hard" &&
      incoming !== "veryHard"
    ) {
      // Dev check: never silently default on a bad level key.
      console.warn(
        `[Game] bridge "start" received invalid level key "${incoming}", falling back to "${DEFAULT_LEVEL}"`,
      );
      this.level = DEFAULT_LEVEL;
    } else {
      this.level = incoming;
    }
    this.levelCfg = LEVELS[this.level];
    this.resetRun();
    this.showGo();
  }

  private resetRun(): void {
    for (const w of this.wisps) w.container.destroy();
    this.wisps = [];
    for (const s of this.trailSpecks) s.destroy();
    this.trailSpecks = [];

    // Restore wizard to full idle state
    if (this.activeSpellOverlay) {
      this.activeSpellOverlay.destroy();
      this.activeSpellOverlay = null;
    }
    this.cancelWizReaction();
    this.wizAnimState = "idle";
    if (this.wiz && this.wiz.active) {
      this.wiz.clearTint();
      this.setWizIdleTexture();
      this.wiz.setPosition(TUNING.WIZ_X, TUNING.WIZ_BOTTOM_Y);
      this.wiz.setAlpha(1);
      this.wiz.setScale(TUNING.WIZ_SCALE);
    }
    if (this.wizIdleTween && this.wizIdleTween.isPaused()) {
      this.wizIdleTween.resume();
    }

    this.wallHP = TUNING.WALL_HP;
    this.score = 0;
    this.streak = 0;
    this.runBestStreak = 0;
    this.correctCount = 0;
    this.wrongCount = 0;
    this.keyboardCasts = 0;
    this.padCasts = 0;
    this.inputLockUntil = 0;
    this.goSecondSpawnPending = false;
    this.spawnInterval = this.levelCfg.spawnStart;
    this.spawnTimer = TUNING.FIRST_SPAWN_DELAY;
    this.refreshKeepFrame();
    this.emitHud();
  }

  private showGo(): void {
    this.goText?.destroy();
    this.goText = this.add
      .text(TUNING.WIDTH / 2, 360, "GO!", {
        fontFamily: FONT,
        fontSize: "64px",
        color: PALETTE.ember,
      })
      .setOrigin(0.5)
      .setDepth(50)
      .setAlpha(0);

    this.tweens.add({
      targets: this.goText,
      alpha: 1,
      duration: 120,
      yoyo: true,
      hold: TUNING.GO_FLASH_MS - 240,
      onComplete: () => {
        this.goText?.destroy();
        this.goText = null;
        this.runStartTime = this.time.now;
        this.running = true;
        this.spawnWisp();
        this.goSecondSpawnPending = true;
      },
    });
  }

  private handleResume(): void {
    this.paused = false;
    this.tweens.timeScale = 1;
  }

  private handleRestart(): void {
    this.running = false;
    this.paused = false;
    this.tweens.timeScale = 1;
    for (const w of this.wisps) w.container.destroy();
    this.wisps = [];
    for (const s of this.trailSpecks) s.destroy();
    this.trailSpecks = [];
    this.emitHud();
  }

  private handleQuit(): void {
    this.running = false;
    this.paused = false;
    this.tweens.timeScale = 1;
    for (const w of this.wisps) w.container.destroy();
    this.wisps = [];
    for (const s of this.trailSpecks) s.destroy();
    this.trailSpecks = [];
    this.emitHud();
  }

  private handleSetPaused(paused: boolean): void {
    this.paused = paused;
    this.tweens.timeScale = paused ? 0 : 1;
  }

  private emitHud(): void {
    bridge.emit(EV.hud, {
      score: this.score,
      streak: this.streak,
      wallHP: this.wallHP,
    });
  }

  /* ----------------------------- cleanup ----------------------------- */

  private cleanup(): void {
    bridge.off(EV.cast, this.boundCast);
    bridge.off(EV.start, this.boundStart);
    bridge.off(EV.resume, this.boundResume);
    bridge.off(EV.restart, this.boundRestart);
    bridge.off(EV.quit, this.boundQuit);
    bridge.off(EV.setPaused, this.boundSetPaused);
    if (this.keyboardEnabled) {
      const kb = this.input?.keyboard;
      if (kb && this.boundKeyDown) kb.off("keydown", this.boundKeyDown);
    }
    if (this.activeSpellOverlay) {
      this.activeSpellOverlay.destroy();
      this.activeSpellOverlay = null;
    }
    // Clean up clouds + portal graphics (UI-redesign Task ID 12).
    this.clouds.forEach((c) => c.img.destroy());
    this.clouds = [];
    if (this.portalGfx) {
      this.portalGfx.destroy();
      this.portalGfx = null;
    }
    this.cancelWizReaction();
    this.running = false;
  }
